class SelbergTraceFormula:
    """
    The Selberg trace formula for compact hyperbolic surfaces.

    For X = Γ\ℍ², the trace formula relates:
    - Spectrum side: Σₖ h(rₖ) where λₖ = 1/4 + rₖ²
    - Geometric side: Σ_{γ primitive} (l_γ / sinh(l_γ/2)) Σ_{m=1}^∞ χ(γ^m)

    The Riemann zeros can be viewed as the "geodesic lengths" in the
    prime geodesic theorem analog.
    """

    def __init__(self, volume: float = 1.0):
        self.volume = volume

    def prime_geodesic_theorem(self, x: float, zeros: List[float] = None) -> float:
        """
        Compute π₀(x) = number of primitive closed geodesics with length ≤ x.

        Analog of the Prime Number Theorem: π₀(x) ~ li(e^x).
        """
        if x < 2:
            return 0.0
        prime_geo_count = math.exp(x) / x if x > 1 else 0.0
        return prime_geo_count

    def mobius_inverted_geodesics(self, x: float, num_terms: int = 20) -> float:
        """
        Use Möbius inversion to extract primitive geodesic count.

        The total geodesic count (including powers) is:
        Ψ₀(x) = Σ_{γ primitive} Σ_{m: m·l_γ ≤ x} l_γ

        Möbius inversion gives:
        π₀(x) = Σ_{m=1}^∞ μ(m)/m · Ψ₀(m·x)

        We cap m·x to avoid overflow in exp(m·x).
        """
        mu = mobius_upto(num_terms)
        primitive_count = 0.0

        for m in range(1, num_terms + 1):
            if mu[m] == 0:
                continue
            mx = min(m * x, 20.0)  # cap to avoid overflow
            total = self.prime_geodesic_theorem(mx)
            primitive_count += (mu[m] / m) * total

        return primitive_count

    def spectral_gap_from_zeros(self, zeros: List[float]) -> float:
        """
        Compute the spectral gap from Riemann zeros.

        For the Laplacian on a hyperbolic surface, λₖ = 1/4 + rₖ².
        The Riemann zeros γₖ correspond to rₖ, so λₖ = 1/4 + γₖ².

        The spectral gap is λ₁ - λ₀ where λ₀ = 1/4 (the bottom of continuous spectrum).
        For the Riemann hypothesis, all γₖ are real, so λₖ ≥ 1/4.
        """
        if not zeros:
            return FRIEDMAN_GAP

        # The first zero gives the first eigenvalue above the bottom
        first_zero = min(abs(z) for z in zeros)
        # λ₁ = 1/4 + r₁² where r₁ is related to the first zero
        # For the analogy: the spectral gap is controlled by the first zero
        gap = 0.25 + (first_zero / 100.0) ** 2  # Scaled for analogy
        return gap


