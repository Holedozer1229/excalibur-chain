    def to_text_score(self) -> str:
        """Convert composition to readable text score."""
        note_names = ['C', 'C#', 'D', 'D#', 'E', 'F', 'F#', 'G', 'G#', 'A', 'A#', 'B']
        lines = []
        lines.append("=" * 80)
        lines.append("HILBERT-PÓLYA COMPOSITION: Riemann Zeros as Musical Eigenvalues")
        lines.append(f"Zeros used: {len(self.zeros)} | Tempo: {self.tempo_bpm} BPM | Time: 4/4")
        lines.append("=" * 80)
        lines.append("")

        for measure in self.measures:
            measure_num = measure['measure']
            lines.append(f"Measure {measure_num:2d} | {measure['time_signature']} |")
            lines.append("-" * 80)
            lines.append(f"  {'Beat':<6} {'Zero':<10} {'γ':<12} {'Counterpt':<10} {'μ(n)':<6} {'sn':<8} {'Prime':<6} {'Vel':<6}")
            lines.append("-" * 80)

            for note in measure['notes']:
                beat = note['beat'] + 1
                note_name = note_names[note['zero_midi'] % 12]
                octave = note['zero_midi'] // 12 - 1
                zero_str = f"{note_name}{octave}"

                if note['counterpoint_midi'] is not None:
                    cp_name = note_names[note['counterpoint_midi'] % 12]
                    cp_octave = note['counterpoint_midi'] // 12 - 1
                    cp_str = f"{cp_name}{cp_octave}"
                else:
                    cp_str = "rest"

                lines.append(
                    f"  {beat:<6} {zero_str:<10} {note['zero_value']:<12.4f} "
                    f"{cp_str:<10} {note['mobius_value']:<6} {note['normalized_spacing']:<8.3f} "
                    f"{'*' if note['is_prime_index'] else ' ':<6} {note['velocity']:<6}"
                )
            lines.append("")

        return "\n".join(lines)

    def to_midi_events(self) -> List[Dict]:
        """Convert to MIDI-like event list."""
        events = []
        tick = 0
        ticks_per_beat = self.tempo_bpm * 4

        duration_map = {
            'whole': 4.0, 'half': 2.0, 'quarter': 1.0,
            'eighth': 0.5, 'sixteenth': 0.25, 'thirty-second': 0.125
        }

        for measure in self.measures:
            for note in measure['notes']:
                duration_ticks = int(duration_map.get(note['duration_type'], 0.5) * ticks_per_beat)

                # Zero voice
                events.append({
                    'tick': tick,
                    'type': 'note_on',
                    'channel': 0,
                    'note': note['zero_midi'],
                    'velocity': note['velocity'],
                    'duration': duration_ticks,
                    'zero_value': note['zero_value'],
                })

                # Counterpoint voice
                if note['counterpoint_midi'] is not None:
                    events.append({
                        'tick': tick,
                        'type': 'note_on',
                        'channel': 1,
                        'note': note['counterpoint_midi'],
                        'velocity': int(note['velocity'] * 0.75),
                        'duration': duration_ticks,
                    })

                tick += duration_ticks

        return events

