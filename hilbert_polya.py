def normalize_spacings(zeros: List[float], num_zeros: int = None) -> List[float]:
    """
    Normalize the zero spacings to mean spacing 1.

    The average density of zeros near t is ~ln(t/2π)/(2π),
    so the mean spacing near t is ~2π/ln(t/2π).
    """
    if num_zeros is None:
        num_zeros = len(zeros)

    spacings = []
    for i in range(num_zeros - 1):
        delta = zeros[i + 1] - zeros[i]
        # Mean spacing at this height
        t_mid = (zeros[i] + zeros[i + 1]) / 2.0
        mean_spacing = 2.0 * math.pi / math.log(t_mid / (2.0 * math.pi))
        # Normalized spacing
        sn = delta / mean_spacing
        spacings.append(sn)

    return spacings


def pair_correlation(zeros: List[float], w_bins: int = 50, w_max: float = 4.0) -> List[Tuple[float, float]]:
    """
    Compute the pair correlation function of normalized spacings.

    For GUE, the pair correlation is:
    R₂(w) = 1 - (sin(πw)/(πw))²

    The Montgomery-Odlyzko law states that Riemann zeros follow GUE statistics.
    """
    spacings = normalize_spacings(zeros)
    if not spacings:
        return []

    # Compute histogram of spacings
    bin_width = w_max / w_bins
    histogram = [0.0] * w_bins

    for s in spacings:
        bin_idx = int(s / bin_width)
        if 0 <= bin_idx < w_bins:
            histogram[bin_idx] += 1.0

    # Normalize to density
    total = sum(histogram)
    if total > 0:
        histogram = [h / total * bin_width for h in histogram]

    # Build result with GUE theoretical curve
    result = []
    for i in range(w_bins):
        w = (i + 0.5) * bin_width
        # GUE theoretical pair correlation
        if abs(w) < 1e-10:
            gue = 1.0
        else:
            gue = 1.0 - (math.sin(math.pi * w) / (math.pi * w)) ** 2
        result.append((w, histogram[i], gue))

    return result


