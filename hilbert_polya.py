def explicit_formula_mertens(x: float, zeros: List[float], num_terms: int = 50) -> float:
    """
    Compute M(x) = Σ_{n≤x} μ(n) using the explicit formula.

    M(x) ≈ -Σ_ρ x^ρ / ρ + log(2π) - 1 - Σ_{k=1}^{∞} x^{1-2k}/(1-2k)

    where the sum is over non-trivial zeros ρ = 1/2 ± iγ.
    """
    # Sum over zeros (pairing conjugate zeros)
    zero_sum = 0.0
    for gamma in zeros[:num_terms]:
        rho = 0.5 + 1j * gamma
        # Pair with conjugate: x^ρ/ρ + x^(1-ρ)/(1-ρ)
        term = (x ** rho) / rho
        term += (x ** (1.0 - rho)) / (1.0 - rho)
        zero_sum += term.real

    # Trivial zero contributions
    trivial = math.log(2.0 * math.pi) - 1.0
    for k in range(1, 5):
        s = 1.0 - 2.0 * k
        trivial -= (x ** s) / s

    mertens_approx = -zero_sum + trivial
    return mertens_approx


def compute_mertens_direct(x_max: int = 100) -> List[int]:
    """Compute M(x) = Σ_{n≤x} μ(n) directly."""
    mu = mobius_upto(x_max)
    mertens = [0] * (x_max + 1)
    running = 0
    for i in range(1, x_max + 1):
        running += mu[i]
        mertens[i] = running
    return mertens


