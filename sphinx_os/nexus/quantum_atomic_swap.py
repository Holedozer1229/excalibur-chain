"""Quantum Atomic Swap — HTLC-based EXCAL to BTC conversion.

This module converts EXCAL back to BTC using Hash-Time-Locked Contracts (HTLC)
with quantum-secured preimages from the spacetime fabric. The preimage is
generated by evolving the quantum state with seed-dependent gates, making each
swap tied to its burn event.

Key concepts:
- HTLC: Hash-Time-Locked Contract for atomic swap
- Quantum preimage: derived from spacetime fabric evolution
- Claim address: BTC destination for reclaimed coins
"""

import hashlib
import hmac
import time
from dataclasses import dataclass, field
from typing import Dict, List, Optional, Tuple

import numpy as np


# ---------------------------------------------------------------------------
# Data Classes
# ---------------------------------------------------------------------------

@dataclass
class SwapPreimage:
    """Quantum-secured preimage for HTLC swap."""
    preimage: bytes       # The secret preimage
    hash_lock: str        # SHA-256 hash of preimage (hex)
    time_lock: int        # Unix timestamp for time lock expiry
    seed: bytes           # Quantum seed used to generate preimage


@dataclass
class AtomicSwap:
    """An atomic swap transaction."""
    swap_id: str          # Unique swap identifier
    preimage: SwapPreimage
    excal_amount: float   # EXCAL amount being swapped
    btc_amount: float     # BTC amount to receive
    claim_address: str    # BTC address to receive funds
    status: str           # 'pending', 'locked', 'claimed', 'refunded'
    htlc_script: str      # HTLC redeem script (hex)
    txid: Optional[str] = None  # Confirmation TXID


# ---------------------------------------------------------------------------
# Quantum Atomic Swap Engine
# ---------------------------------------------------------------------------

class QuantumAtomicSwap:
    """Converts EXCAL to BTC using quantum-secured HTLC atomic swaps.

    Args:
        time_lock_delta: Time lock duration in seconds (default 1 hour).
        seed: Random seed for quantum preimage generation.
    """

    def __init__(self, time_lock_delta: int = 3600, seed: Optional[int] = None):
        self.time_lock_delta = time_lock_delta
        self.rng = np.random.RandomState(seed)
        self.swaps: Dict[str, AtomicSwap] = {}

    def generate_preimage(self, seed_bytes: bytes) -> SwapPreimage:
        """Generate a quantum-secured preimage from seed bytes.

        The preimage is derived by evolving a quantum state with seed-dependent
        gates, making each swap tied to its originating event.

        Args:
            seed_bytes: Seed bytes (e.g., burn TXID hash).

        Returns:
            SwapPreimage with hash lock and time lock.
        """
        # Evolve quantum state with seed-dependent gates
        state = np.zeros(32, dtype=np.float64)
        for i, b in enumerate(seed_bytes[:32]):
            state[i % 32] += b / 255.0

        # Apply quantum gate sequence
        gates = ['H', 'T', 'S', 'X']
        for i in range(64):
            gate = gates[i % len(gates)]
            idx = int(state[i % 32] * 32) % 32
            angle = (0.5 if gate == 'H' else 0.25 if gate == 'T' else 0.35 if gate == 'S' else 0.75) * np.pi
            state[idx] += angle

        # Generate preimage from evolved state
        preimage = bytes([int(abs(s) * 255) % 256 for s in state])

        # Compute hash lock
        hash_lock = hashlib.sha256(preimage).hexdigest()

        # Set time lock
        time_lock = int(time.time()) + self.time_lock_delta

        return SwapPreimage(
            preimage=preimage,
            hash_lock=hash_lock,
            time_lock=time_lock,
            seed=seed_bytes,
        )

    def build_htlc_script(self, preimage: SwapPreimage,
                          claim_address: str, refund_address: str,
                          btc_amount_sats: int) -> str:
        """Build an HTLC redeem script.

        Args:
            preimage: The swap preimage with hash lock.
            claim_address: BTC address for the claimant.
            refund_address: BTC address for refund.
            btc_amount_sats: Amount in satoshis.

        Returns:
            HTLC script in hex format.
        """
        # Simplified HTLC script (P2SH format)
        # OP_HASH160 <H> OP_EQUAL OP_IF <A> OP_ELSE n OP_ENDIF
        h = bytes.fromhex(preimage.hash_lock)
        hash160 = hashlib.sha256(h).digest()[:20]

        # Build script (simplified representation)
        script_parts = [
            "a9",  # OP_HASH160
            "14",  # push 20 bytes
            hash160.hex(),
            "87",  # OP_EQUAL
            "63",  # OP_IF
            "76a914",  # OP_DUP OP_HASH160
            claim_address[:40],  # simplified claim pubkey hash
            "88ac",  # OP_EQUALVERIFY OP_CHECKSIG
            "67",  # OP_ELSE
            f"{preimage.time_lock:04x}",  # nLockTime
            "88",  # OP_CHECKLOCKTIMEVERIFY
            "76a914",  # OP_DUP OP_HASH160
            refund_address[:40],  # simplified refund pubkey hash
            "88ac",  # OP_EQUALVERIFY OP_CHECKSIG
            "68",  # OP_ENDIF
        ]
        return "".join(script_parts)

    def create_swap(self, excal_amount: float, btc_amount: float,
                    seed_bytes: bytes, claim_address: str,
                    refund_address: str = "1RefundAddressXXXXXXXXXXXXXXX") -> AtomicSwap:
        """Create a new atomic swap.

        Args:
            excal_amount: EXCAL amount being swapped.
            btc_amount: BTC amount to receive.
            seed_bytes: Seed for quantum preimage.
            claim_address: BTC address to receive funds.
            refund_address: BTC address for refund if swap fails.

        Returns:
            AtomicSwap object.
        """
        # Generate quantum preimage
        preimage = self.generate_preimage(seed_bytes)

        # Build HTLC script
        btc_sats = int(btc_amount * 100_000_000)
        htlc_script = self.build_htlc_script(preimage, claim_address,
                                              refund_address, btc_sats)

        # Create swap
        swap_id = hashlib.sha256(
            f"{excal_amount}{btc_amount}{preimage.hash_lock}".encode()
        ).hexdigest()[:16]

        swap = AtomicSwap(
            swap_id=swap_id,
            preimage=preimage,
            excal_amount=excal_amount,
            btc_amount=btc_amount,
            claim_address=claim_address,
            status='locked',
            htlc_script=htlc_script,
        )

        self.swaps[swap_id] = swap
        return swap

    def execute_swap(self, swap_id: str) -> Tuple[bool, str]:
        """Execute (claim) an atomic swap.

        Args:
            swap_id: The swap to claim.

        Returns:
            Tuple of (success, message).
        """
        swap = self.swaps.get(swap_id)
        if swap is None:
            return False, f"Swap {swap_id} not found"

        if swap.status != 'locked':
            return False, f"Swap {swap_id} is {swap.status}, not claimable"

        # Simulate claiming with preimage
        swap.status = 'claimed'
        swap.txid = hashlib.sha256(
            swap.preimage.preimage
        ).hexdigest()[:64]

        return True, f"Swap claimed: {swap.txid}"

    def set_claim_address(self, claim_address: str) -> None:
        """Set default claim address for new swaps.

        Args:
            claim_address: BTC P2PKH address.
        """
        self.default_claim_address = claim_address

    def get_swap(self, swap_id: str) -> Optional[AtomicSwap]:
        """Get a swap by ID.

        Args:
            swap_id: The swap identifier.

        Returns:
            AtomicSwap or None if not found.
        """
        return self.swaps.get(swap_id)
