    print()
    
    # Factor p-1
    print(f"  Factorization of p-1 = {p - 1}:")
    temp = p - 1
    factors = []
    d = 2
    while d * d <= temp:
        while temp % d == 0:
            factors.append(d)
            temp //= d
        d += 1
    if temp > 1:
        factors.append(temp)
    print(f"    {' × '.join(map(str, factors))}")
    print()
    
    # Order of 2 mod p
    print(f"  Order of 2 mod p:")
    order = 1
    val = 2 % p
    while val != 1:
        val = (val * 2) % p
        order += 1
        if order > p - 1:
            break
    print(f"    ord_p(2) = {order}")
    print(f"    (p-1) / ord = {(p - 1) / order if order > 0 else 'N/A'}")
    print()
    
    # Discrete log relationship
    print(f"  The equation: 2^{GENESIS_NONCE} ≡ {TARGET_H} (mod {p})")
    print(f"  Verified: {pow(2, GENESIS_NONCE, p) == TARGET_H}")
    print()
    
    # What is h in terms of the group structure?
    print(f"  Target h = {TARGET_H}")
    print(f"  h is {'prime' if is_prime(TARGET_H) else 'composite'}")
    
    # Factor h
    temp = TARGET_H
    factors_h = []
    d = 2
    while d * d <= temp:
        while temp % d == 0:
            factors_h.append(d)
            temp //= d
        d += 1
    if temp > 1:
        factors_h.append(temp)
    print(f"  Factorization of h: {' × '.join(map(str, factors_h))}")
    print()
    
    return p

